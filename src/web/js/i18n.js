  let lang = "zh";

  function storage() { return global.GobanHost || null; }

  function load() {
    const h = storage();
    try {
      const v = h && h.storageGet(KEY);
      if (v === "en" || v === "zh") lang = v;
    } catch (_) {}
    return lang;
  }

  function current() { return lang; }

  function setLang(next) {
    if (next !== "en" && next !== "zh") return;
    lang = next;
    const h = storage();
    try { if (h) h.storageSet(KEY, lang); } catch (_) {}
    document.documentElement.setAttribute("lang", lang === "en" ? "en" : "zh-CN");
    apply();
  }

  /** Look up `key`, filling {placeholders} from `params`; falls back to 中文. */
  function t(key, params) {
    const table = DICT[lang] || DICT.zh;
    let s = table[key];
    if (s == null) s = DICT.zh[key];
    if (s == null) return key;
    if (params) {
      s = s.replace(/\{(\w+)\}/g, (m, name) =>
        Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : m);
    }
    return s;
  }

  /** Translate everything tagged in the static markup. */
  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
    });
    scope.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
    const title = document.querySelector("title");
    if (title) title.textContent = t("app.name");
  }

  global.GobanI18n = { t, apply, setLang, lang: current, load, DICT };
