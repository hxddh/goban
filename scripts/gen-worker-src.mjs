/**
 * Generate js/worker-src.js — the engine sources embedded as one string.
 *
 * Why: the packaged app serves assets through a zero:// WKURLSchemeHandler
 * that returns bare NSURLResponse objects. <script> tags load fine, but
 * fetch() (spec-strict) rejects such responses, so the Blob worker could
 * not obtain its sources at runtime. Embedding them at build time makes
 * worker construction fetch-free: page loads worker-src.js via <script>,
 * app builds the Blob from window.GOBAN_WORKER_SRC.
 *
 * Usage: node scripts/gen-worker-src.mjs <output-dir>   (default frontend/dist/js)
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const srcDir = path.join(root, "src/web/js");
const outDir = path.resolve(root, process.argv[2] || "frontend/dist/js");

const FILES = ["core.js", "ai.js", "ai2.js", "ai-worker.js"];
const joined = FILES.map((f) =>
  fs.readFileSync(path.join(srcDir, f), "utf8")
).join("\n;\n");

const out =
  "/* generated by scripts/gen-worker-src.mjs — do not edit */\n" +
  "window.GOBAN_WORKER_SRC = " +
  JSON.stringify(joined) +
  ";\n";

fs.mkdirSync(outDir, { recursive: true });
const outPath = path.join(outDir, "worker-src.js");
fs.writeFileSync(outPath, out);
console.log("wrote " + outPath + " (" + out.length + " bytes)");
